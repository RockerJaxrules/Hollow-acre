def bold(rows):
    """thicken one pixel to the right"""
    w = max(len(r) for r in rows) + 1
    out = []
    for r in rows:
        r = r.ljust(w - 1, '.') + '.'
        out.append(''.join('#' if (r[x] == '#' or (x > 0 and r[x - 1] == '#')) else '.' for x in range(w)))
    return out


# The bold cut is the regular one thickened to the right, except where that would fill a one-pixel counter and turn a
# letter into a block (judge, business ledger: bold m printed as a solid block, M and W read as H). These are drawn by hand:
# two-pixel stems, the counters kept open, and the M's diagonals meeting two pixels below the cap line (the W mirrors it).
BOLD = {
    'M': ['##...##', '###.###', '##.#.##', '##.#.##', '##...##', '##...##', '##...##'],
    'W': ['##...##', '##...##', '##...##', '##.#.##', '##.#.##', '###.###', '##...##'],
    'N': ['##...##', '###..##', '####.##', '##.####', '##..###', '##...##', '##...##'],
    'm': ['.......', '.......', '######.', '##.#.##', '##.#.##', '##.#.##', '##.#.##'],
    'w': ['.......', '.......', '##...##', '##...##', '##.#.##', '##.#.##', '.##.##.'],
}


def build(name, style, glyphs):
    order = ['.notdef'] + ['u%04X' % ord(c) for c in glyphs]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(c): 'u%04X' % ord(c) for c in glyphs})
    gl, adv = {}, {}
    pen = TTGlyphPen(None); pen.moveTo((0, 0)); pen.lineTo((0, 700)); pen.lineTo((500, 700)); pen.lineTo((500, 0)); pen.closePath()
    gl['.notdef'] = pen.glyph(); adv['.notdef'] = (600, 0)
    for c, rows in glyphs.items():
        pen = TTGlyphPen(None); w = max(len(r) for r in rows)
        for ry, row in enumerate(rows):
            x = 0
            while x < len(row):   # one rectangle per horizontal run of ink, wound clockwise (TrueType)
                if row[x] != '#': x += 1; continue
                x1 = x
                while x1 < len(row) and row[x1] == '#': x1 += 1
                top = (7 - ry) * U; bot = top - U
                pen.moveTo((x * U, bot)); pen.lineTo((x * U, top)); pen.lineTo((x1 * U, top)); pen.lineTo((x1 * U, bot)); pen.closePath()
                x = x1
        gl['u%04X' % ord(c)] = pen.glyph(); adv['u%04X' % ord(c)] = ((w + 1) * U, 0)
    fb.setupGlyf(gl)
    fb.setupHorizontalMetrics({k: (adv[k][0], 0) for k in order})
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({'familyName': 'Hollow Pixel', 'styleName': style, 'uniqueFontIdentifier': name, 'fullName': name,
                       'psName': name.replace(' ', ''), 'version': 'Version 1.0', 'copyright': 'Hollow Acre, drawn for the game'})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=800, usWinDescent=200,
                usWeightClass=700 if style == 'Bold' else 400, fsSelection=0x20 if style == 'Bold' else 0x40)
    fb.setupPost()
    if style == 'Bold': fb.font['head'].macStyle = 1
    b = io.BytesIO(); fb.save(b); return b.getvalue()


