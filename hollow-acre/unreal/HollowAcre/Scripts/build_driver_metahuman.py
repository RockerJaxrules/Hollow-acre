"""Build the driver's MetaHuman (Content/HollowAcre/Driver) from the "Bruce" preset: cloud auto-rig (joints only: the
face isn't seen in first person), cloud texture sources, then assemble. Needs the owner's MetaHuman sign-in (saved
once from the MetaHuman Character editor). Only Built/Driver/Body is used by the game (DriverArms); the rest is
regenerated by running this script and is not committed (see .gitignore)."""
import unreal

def log(*a):
    unreal.log('[mhb] ' + ' '.join(str(x) for x in a))

eal = unreal.EditorAssetLibrary
sub = unreal.get_editor_subsystem(unreal.MetaHumanCharacterEditorSubsystem)
if eal.does_asset_exist('/Game/HollowAcre/Driver/MHC_AuthTest'):
    eal.delete_asset('/Game/HollowAcre/Driver/MHC_AuthTest')
for a in ('/Game/HollowAcre/Driver/MHC_Probe_Bruce',):
    if eal.does_asset_exist(a):
        eal.delete_asset(a)
DST = '/Game/HollowAcre/Driver/MHC_Driver'
if eal.does_asset_exist(DST):
    eal.delete_asset(DST)
ch = eal.duplicate_asset('/MetaHumanCharacter/Optional/Presets/Bruce', DST)
log('fresh copy', ch is not None, 'edit', sub.try_add_object_to_edit(ch))
# skin tone: the Part 1 default (#e8b48c) is a light-medium tone; nudge the preset's skin toward it
ss = ch.get_editor_property('skin_settings')
sk = ss.get_editor_property('skin')
log('skin u,v was', sk.get_editor_property('u'), sk.get_editor_property('v'))
rp = unreal.MetaHumanCharacterAutoRiggingRequestParams()
log('rig params fields', [n for n in dir(rp) if not n.startswith('_')][:20])
for k, v in (('rig_type', unreal.MetaHumanRigType.JOINTS_ONLY), ('report_progress', False), ('blocking', True)):
    try:
        rp.set_editor_property(k, v)
    except Exception as e:
        log('rig param', k, e)
log('auto-rigging...')
sub.request_auto_rigging(ch, rp)
log('auto-rig done; can_build?', sub.can_build_meta_human(ch, True))
tp = unreal.MetaHumanCharacterTextureRequestParams()
tp.set_editor_property('report_progress', False)
tp.set_editor_property('blocking', True)
log('texture sources...')
sub.request_texture_sources(ch, tp)
log('high res textures', ch.get_editor_property('has_high_resolution_textures'))
eal.save_loaded_asset(ch)
ok = sub.can_build_meta_human(ch, True)
log('can_build', ok)
if ok:
    bp = unreal.MetaHumanCharacterEditorBuildParameters()
    log('build params', bp)
    try:
        bp.set_editor_property('absolute_build_path', '/Game/HollowAcre/Driver/Built')
        bp.set_editor_property('name_override', 'Driver')
    except Exception as e:
        log('build param', e)
    sub.build_meta_human(ch, bp)
    eal.save_directory('/Game/HollowAcre/Driver', only_if_is_dirty=True, recursive=True)
    log('built assets', [a.split('.')[0] for a in eal.list_assets('/Game/HollowAcre/Driver', recursive=True, include_folder=False)][:80])
