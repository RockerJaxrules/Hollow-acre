"""The husk's mouth from the MetaHuman face rig: Saved/Generated/Husk/face_poses.json (the face's joints at rest, with
the jaw open, and screaming, as the rig (RigLogic) sets them: recorded by a game run with -huskfacebake, see
Scripts/husk_face_bake.py) -> Source/HollowAcre/HuskFacePoses.inl, each moved joint's change from rest (its local move
and turn) for the open jaw and the scream. The neck's joints are left out (the body poses the neck).
Run: python hollow-acre/unreal/tools/husk_face_poses.py
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.join(HERE, '..', 'HollowAcre')
SRC = os.path.join(PROJ, 'Saved', 'Generated', 'Husk', 'face_poses.json')
OUT = os.path.join(PROJ, 'Source', 'HollowAcre', 'HuskFacePoses.inl')


def qmul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return (aw * bx + ax * bw + ay * bz - az * by,
            aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw,
            aw * bw - ax * bx - ay * by - az * bz)


def qinv(q):
    return (-q[0], -q[1], -q[2], q[3])


def delta(rest, pose):
    """The pose's change from rest: its move (in the parent's frame) and its turn (in its own frame)."""
    dt = [pose[i] - rest[i] for i in range(3)]
    dq = qmul(qinv(rest[3:]), pose[3:])
    if dq[3] < 0:
        dq = tuple(-v for v in dq)
    return dt, dq


def main():
    poses = json.load(open(SRC, encoding='utf-8'))
    rest, opened, scream = poses['rest'], poses['open'], poses['scream']
    rows, dropped = [], []
    for name in rest:
        if 'Neck' in name:
            continue
        do = delta(rest[name], opened[name])
        ds = delta(rest[name], scream[name])
        move = max(math.sqrt(sum(v * v for v in d[0])) for d in (do, ds))
        turn = max(math.degrees(2 * math.acos(min(1.0, abs(d[1][3])))) for d in (do, ds))
        if move < 0.003 and turn < 0.03:
            continue
        if move > 8.0:                  # not the face's own motion: a joint hung from the neck the body moved
            dropped.append('%s (%.0f cm)' % (name, move))
            continue
        rows.append((name, do, ds))
    fmt = lambda d: '{%.5ff, %.5ff, %.5ff, %.7ff, %.7ff, %.7ff, %.7ff}' % (*d[0], *d[1])
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/husk_face_poses.py from the MetaHuman face rig (RigLogic): each moved joint of the\n'
                '// husk\'s face, its change from rest (move x y z in its parent\'s frame, cm; turn as a quaternion x y z w in\n'
                '// its own frame) with the jaw open, and screaming. Do not edit by hand.\n')
        f.write('static const FHuskFacePoseRow GHuskFacePoses[] = {\n')
        for name, do, ds in rows:
            f.write('\t{TEXT("%s"), %s, %s},\n' % (name, fmt(do), fmt(ds)))
        f.write('};\n')
    print('wrote', OUT, len(rows), 'joints of', len(rest), '; left out', dropped)


if __name__ == '__main__':
    main()
