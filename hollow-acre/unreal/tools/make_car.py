# ---------------- mesh building ----------------
class Mesh:
    def __init__(self):
        self.parts = []   # (material, verts (N,3), uvs (N,2), tris (M,3))

    def add(self, mat, v, uv, tris, face=None, toward=None):
        """face: 'out' (away from the part's centre) / 'in'; toward: a point the surface should face (e.g. the eye)."""
        v, uv, tris = np.asarray(v, float), np.asarray(uv, float), np.asarray(tris, int)
        tris = orient(v, tris, face, toward)
        self.parts.append((mat, v, uv, tris))

    def write(self, path):
        with open(path, 'w', newline='\n') as fh:
            fh.write('# generated by hollow-acre/unreal/tools/make_car.py\n')
            vo = 0
            for i, (mat, v, uv, tris) in enumerate(self.parts):
                fh.write(f'usemtl {mat}\ns 1\n')  # no 'o' lines: Unreal would import every object as its own mesh
                fh.write(''.join(f'v {a + SHIFT_X:.3f} {-b:.3f} {c:.3f}\n' for a, b, c in v))  # Unreal reads OBJ with Y mirrored
                fh.write(''.join(f'vt {a:.4f} {b:.4f}\n' for a, b in uv))
                fh.write(''.join(f'f {c + vo + 1}/{c + vo + 1} {b + vo + 1}/{b + vo + 1} {a + vo + 1}/{a + vo + 1}\n' for a, b, c in tris))
                vo += len(v)


def orient(v, tris, face, toward):
    if face is None and toward is None:
        return tris
    a, b, c = v[tris[:, 0]], v[tris[:, 1]], v[tris[:, 2]]
    n = np.cross(b - a, c - a)
    mid = (a + b + c) / 3
    if toward is not None:
        want = np.asarray(toward, float) - mid
    else:
        want = mid - v.mean(0)
        if face == 'in':
            want = -want
    flip = np.einsum('ij,ij->i', n, want) < 0
    out = tris.copy()
    out[flip] = out[flip][:, ::-1]
    return out


def grid(rows, cols, wrap_cols=False):
    t = []
    cc = cols if wrap_cols else cols - 1
    for r in range(rows - 1):
        for c in range(cc):
            c2 = (c + 1) % cols
            a, b, d, e = r * cols + c, r * cols + c2, (r + 1) * cols + c, (r + 1) * cols + c2
            t += [(a, d, b), (b, d, e)]
    return t


def loft(sections, closed=False, uv_scale=None):
    """sections: list of (M,3) point rows. UV: along rows by arc length (cm / TEX_CM), across sections likewise."""
    S = np.array(sections, float)
    R, M = S.shape[:2]
    if closed:
        S = np.concatenate([S, S[:, :1]], 1)
        M += 1
    du = np.concatenate([np.zeros((R, 1)), np.cumsum(np.linalg.norm(np.diff(S, axis=1), axis=2), 1)], 1)
    dv = np.concatenate([np.zeros((1, M)), np.cumsum(np.linalg.norm(np.diff(S, axis=0), axis=2), 0)], 0)
    sc = uv_scale or TEX_CM
    uv = np.stack([du / sc, dv / sc], -1).reshape(-1, 2) if uv_scale != 'unit' else \
        np.stack(np.meshgrid(np.linspace(0, 1, M), np.linspace(0, 1, R)), -1).reshape(-1, 2)
    return S.reshape(-1, 3), uv, grid(R, M)


def frame_from(n):
    n = n / np.linalg.norm(n)
    a = np.array([0, 0, 1.0]) if abs(n[2]) < 0.9 else np.array([1.0, 0, 0])
    u = np.cross(a, n)
    u /= np.linalg.norm(u)
    return u, np.cross(n, u), n


def superellipsoid(c, axes, rx, ry, rz, e=0.35, nu=24, nv=14):
    """Rounded box/blob at c with local axes (3 unit vectors) and radii; e < 1 gives flatter sides."""
    ax, ay, az = axes
    pts, uvs = [], []

    def sp(w, m):
        return np.sign(w) * np.abs(w) ** m
    for j in range(nv + 1):
        th = -math.pi / 2 + math.pi * j / nv
        for i in range(nu):
            ph = 2 * math.pi * i / nu
            x = rx * sp(math.cos(th), e) * sp(math.cos(ph), e)
            y = ry * sp(math.cos(th), e) * sp(math.sin(ph), e)
            z = rz * sp(math.sin(th), e)
            pts.append(c + ax * x + ay * y + az * z)
            uvs.append((i / nu * (rx + ry) / 6, j / nv * rz / 3))
    t = grid(nv + 1, nu, wrap_cols=True)
    return np.array(pts), np.array(uvs), t


def tube(path, prof, closed_path=False):
    """Sweep a closed cross-section prof (K,2) along path (N,3) with parallel-transport frames."""
    path = np.asarray(path, float)
    N = len(path)
    tang = np.gradient(path, axis=0)
    if closed_path:
        tang = np.roll(path, -1, 0) - np.roll(path, 1, 0)
    tang /= np.linalg.norm(tang, axis=1, keepdims=True)
    u, _, _ = frame_from(tang[0])
    rows = []
    for i in range(N):
        u = u - tang[i] * np.dot(u, tang[i])
        u /= np.linalg.norm(u)
        w = np.cross(tang[i], u)
        rows.append([path[i] + u * a + w * b for a, b in prof])
    if closed_path:
        rows.append(rows[0])
    v, uv, t = loft(rows, closed=True)
    # face outward from the centre line (orienting away from the whole part's centre turns a ring's inner half inside out)
    K = len(prof) + 1
    centres = np.repeat(np.array(list(path) + ([path[0]] if closed_path else [])), K, axis=0)
    t = np.array(t)
    a, b, c = v[t[:, 0]], v[t[:, 1]], v[t[:, 2]]
    nrm = np.cross(b - a, c - a)
    want = (a + b + c) / 3 - centres[t[:, 0]]
    flip = np.einsum('ij,ij->i', nrm, want) < 0
    t[flip] = t[flip][:, ::-1]
    return v, uv, t


def ellipse(a, b, k=12):
    return [(a * math.cos(2 * math.pi * i / k), b * math.sin(2 * math.pi * i / k)) for i in range(k)]


def disc(c, n, up, r, uv_c, uv_r, k=48):
    """A flat round face (gauge dial): UV mapped into a circle of the atlas."""
    n = n / np.linalg.norm(n)
    upv = up - n * np.dot(up, n)
    upv /= np.linalg.norm(upv)
    side = np.cross(upv, n)
    v, uv, t = [c], [uv_c], []
    for i in range(k):
        a = 2 * math.pi * i / k
        v.append(c + side * math.cos(a) * r + upv * math.sin(a) * r)
        # 'side' points to the driver's left, and Unreal flips V on import: both signs flip so the dial reads upright
        uv.append((uv_c[0] - math.cos(a) * uv_r[0], uv_c[1] + math.sin(a) * uv_r[1]))
        t.append((0, 1 + i, 1 + (i + 1) % k))
    return np.array(v), np.array(uv), t


def smoothstep(a, b, x):
    t = min(max((x - a) / (b - a), 0.0), 1.0)
    return t * t * (3 - 2 * t)


