def dashboard(m):
    """One lofted surface from the left door to the right door; recessed behind the wheel for the cluster."""
    ys = np.concatenate([np.linspace(-34, -22, 5), np.linspace(-21, 21, 22), np.linspace(22, YC + 70, 26)])
    rows = []
    for y in ys:
        b = smoothstep(-24, -15, y) * (1 - smoothstep(15, 24, y))     # 1 behind the wheel (cluster recess)
        flat = [(86, 96.0), (74, 96.2), (63, 95.2), (55, 93.4), (50.5, 90.5), (48.5, 86.5),
                (48, 82), (47.5, 76), (46, 70), (43, 64), (40, 59), (39, 54)]
        recess = [(86, 96.0), (74, 96.2), (66, 96.0), (61, 95.5), (59.5, 92), (59.5, 88), (53, 85.5), (49, 80),
                  (46.5, 72), (43, 64), (40, 59), (39, 54)]
        rows.append([(x0 + (x1 - x0) * b, y, z0 + (z1 - z0) * b) for (x0, z0), (x1, z1) in zip(flat, recess)])
    v, uv, t = loft(np.array(rows))
    m.add('dash', v, uv, t, toward=EYE + np.array([-20, 0, 10]))

    # instrument binnacle: an arched hood over the cluster, with a soft lip
    rows = []
    for y in np.linspace(-21, 21, 22):
        e = 1 - (abs(y) / 21) ** 4
        lip_z = 96.0 + 6.0 * e
        rows.append([(67, y, 96.0), (61.5, y, 96.0 + 5.0 * e), (55.5, y, lip_z), (53.2, y, lip_z - 1.2 * e), (53.6, y, lip_z - 2.4 * e)])
    v, uv, t = loft(rows)
    m.add('dash', v, uv, t, toward=EYE + np.array([0, 0, 30]))

    # cluster: dark face, two big dials and two small, needles
    face_c = np.array([58.5, 0, 93.0])
    n = np.array([-math.cos(math.radians(14)), 0, math.sin(math.radians(14))])   # tilted back toward the eye
    up = np.array([0, 0, 1.0])
    u, w = np.array([0, 1.0, 0]), np.cross(n, np.array([0, 1.0, 0]))
    w = -w if w[2] < 0 else w
    rows = [[face_c + u * yy + w * zz for yy in np.linspace(-19, 19, 8)] for zz in np.linspace(-6.5, 6.5, 4)]
    v, uv, t = loft(rows)
    m.add('cluster', v, uv, t, toward=EYE)
    # speedometer (left half of the atlas) at about 22 mph, tachometer (right half) at about 1800 rpm; the dial art runs
    # from 225 degrees (zero, lower left) clockwise to -45 degrees (full scale, lower right)
    dials = [(-8.5, 0.5, 6.2, (0.25, 0.5), (0.24, 0.48), 225 - 270 * 22 / 140),
             (8.5, 0.5, 6.2, (0.75, 0.5), (0.24, 0.48), 225 - 270 * 1.8 / 8)]
    for yy, zz, r, uvc, uvr, needle_deg in dials:
        c = face_c + u * yy + w * zz + n * 0.3   # n faces the driver: in front of the panel
        dv, duv, dt = disc(c, n, up, r, uvc, uvr)
        m.add('gauges', dv, duv, dt, toward=EYE)
        # needle: a thin tapered blade from the hub (u is the driver's right, w is up on the dial)
        ang = math.radians(needle_deg)
        dirv = (u * math.cos(ang) + w * math.sin(ang))
        perp = np.cross(n, dirv)
        hub = c + n * 0.25
        nv_ = [hub - perp * 0.22, hub + perp * 0.22, hub + dirv * r * 0.88 + perp * 0.06, hub + dirv * r * 0.88 - perp * 0.06,
               hub - dirv * 0.9]
        m.add('needle', nv_, [(0, 0)] * 5, [(0, 2, 1), (0, 3, 2), (0, 1, 4)], toward=EYE)
        hv, huv, ht = superellipsoid(hub + n * 0.2, (u, w, n), 0.7, 0.7, 0.35, e=0.8, nu=12, nv=6)
        m.add('dash', hv, huv, ht, face='out')


