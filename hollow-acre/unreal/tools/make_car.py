    def ticks(cx, cy, r, a0, a1, vmax, major, minor, labels=True, font=None, rlab=78, lab_fmt=str):
        n = int(round(vmax / minor))
        for i in range(n + 1):
            val = i * minor
            a = math.radians(a0 + (a1 - a0) * val / vmax)
            is_major = abs(val / major - round(val / major)) < 1e-6
