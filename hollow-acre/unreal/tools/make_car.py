def steering_wheel(m):
    c = WHEEL_C
    n = np.array([-math.cos(WHEEL_TILT), 0, math.sin(WHEEL_TILT)])   # faces the driver
    u = np.array([0, 1.0, 0])
    v = np.cross(n, u)
    v = -v if v[2] < 0 else v
    R = 18.5
    ring = [c + u * R * math.cos(2 * math.pi * i / 64) + v * R * math.sin(2 * math.pi * i / 64) for i in range(64)]
    # the rim is a little deeper (toward the driver) than it is wide, like a real grip
    prof = [(1.9 * math.cos(a), 2.2 * math.sin(a)) for a in np.linspace(0, 2 * math.pi, 18, endpoint=False)]
    tv, tuv, tt = tube(ring, prof, closed_path=True)
    m.add('leather', tv, tuv, tt)
    hub = c - n * 2.2
    hv, huv, ht = superellipsoid(hub, (u, v, n), 10.5, 8.0, 3.2, e=0.35, nu=32, nv=12)
    m.add('hub', hv, huv, ht, face='out')
    # spokes at 3, 9 (a little below the middle) and 6 o'clock: flat, widening into the rim
    for ang in (-12.0, 192.0, 270.0):
        a = math.radians(ang)
        d = u * math.cos(a) + v * math.sin(a)
        rows = []
        for t in np.linspace(7.0, R - 1.0, 7):
            wdt = 3.8 + 1.4 * (t / R) ** 3
            side = np.cross(n, d)
            p = c + d * t - n * (1.3 - 0.6 * t / R)
            rows.append([p - side * wdt + n * 0.5, p - side * wdt - n * 0.7, p + side * wdt - n * 0.7, p + side * wdt + n * 0.5])
        sv, suv, st = loft(rows, closed=True)
        m.add('dash', sv, suv, st, face='out')
    # column shroud into the dash, with the indicator (left) and wiper (right) stalks
    rows = []
    for k, t in enumerate(np.linspace(4, 24, 6)):
        p = c - n * t
        rx, rz = 4.0 + 1.2 * k / 5, 3.6 + 1.0 * k / 5
        rows.append([p + u * rx * math.cos(q) + v * rz * math.sin(q) for q in np.linspace(0, 2 * math.pi, 20, endpoint=False)])
    sv, suv, st = loft(rows, closed=True)
    m.add('dash', sv, suv, st, face='out')
    for side, drop, length in ((-1, 1.2, 13.0), (1, 0.6, 12.0)):
        base = c - n * 8.0 + u * side * 4.4 - v * drop
        tip = base + u * side * length - v * 1.6 + n * 1.5
        path = [base + (tip - base) * s for s in np.linspace(0, 1, 6)]
        pv, puv, pt = tube(path, ellipse(0.55, 0.55, 10))
        m.add('dash', pv, puv, pt)
        kv, kuv, kt = superellipsoid(tip, (u, v, n), 1.4, 0.75, 0.75, e=0.8, nu=12, nv=6)
        m.add('dash', kv, kuv, kt, face='out')


def windshield_edges():
    """Base and top edges of the windshield (bowed slightly forward in the middle)."""
    base, top = [], []
    for s in np.linspace(-1, 1, 25):
        base.append((84 + 5 * (1 - s * s), YC + 66 * s, 96.6))
        top.append((14 + 3 * (1 - s * s), YC + 62 * s, 141.0))
    return np.array(base), np.array(top)


def cabin(m, glass):
    base, top = windshield_edges()
    # windshield: U across from the driver's side to the passenger side, V from the roof edge down to the dash
    rows = [top + (base - top) * t for t in np.linspace(0, 1, 12)]
    v, uv, t = loft(rows, uv_scale='unit')
    glass.add('windshield', v, uv, t, toward=EYE)
    # A pillars: padded trim along each side edge of the glass, curving into the roof rail
    for i, side in ((0, -1), (-1, 1)):
        b, tp = base[i], top[i]
        path = [b + (tp - b) * s + np.array([0, side * 1.5, 0]) for s in np.linspace(0, 1, 10)]
        path += [tp + np.array([-12 * s, side * (1.5 + 2 * s), 1.5 * s]) for s in np.linspace(0.15, 1, 5)]
        pv, puv, pt = tube(path, ellipse(4.2, 2.6, 14))
        m.add('trim', pv, puv, pt)
    # headliner: a gently domed fabric panel; its front edge thickens into the header above the glass
    rows = []
    for x in np.linspace(16, -110, 14):
        rows.append([(x, YC + s * 66, 143.5 + 2.2 * (1 - s * s)) for s in np.linspace(-1, 1, 20)])
    v, uv, t = loft(rows)
    m.add('headliner', v, uv, t, toward=EYE)
    hv, huv, ht = tube([(15, YC + 62 * s, 141.8) for s in np.linspace(-1, 1, 16)], ellipse(2.4, 1.6, 12))
    m.add('trim', hv, huv, ht)
    # sun visors folded up, and the rear-view mirror on its stem
    X = np.array([1.0, 0, 0]); Y = np.array([0, 1.0, 0]); Z = np.array([0, 0, 1.0])
    for cy, ry in ((-12.0, 17.0), (YC + 30, 17.0)):
        sv, suv, st = superellipsoid(np.array([6.0, cy, 140.6]), (X, Y, Z), 7.5, ry, 1.1, e=0.3, nu=24, nv=8)
        m.add('headliner', sv, suv, st, face='out')
    stem = [np.array([17.0, YC, 140.5]), np.array([12.0, YC, 133.0])]
    pv, puv, pt = tube([stem[0] + (stem[1] - stem[0]) * s for s in np.linspace(0, 1, 4)], ellipse(0.8, 0.8, 10))
    m.add('dash', pv, puv, pt)
    mirror_axes = (np.array([math.cos(math.radians(-14)), math.sin(math.radians(-14)), 0]),
                   np.array([-math.sin(math.radians(-14)), math.cos(math.radians(-14)), 0]), Z)
    mv, muv, mt = superellipsoid(np.array([11.0, YC, 130.0]), mirror_axes, 2.2, 12.0, 3.4, e=0.25, nu=28, nv=10)
    m.add('dash', mv, muv, mt, face='out')
    fv, fuv, ft = superellipsoid(np.array([8.8, YC, 130.0]) + mirror_axes[0] * 0.0, mirror_axes, 0.15, 11.2, 2.8, e=0.15, nu=24, nv=6)
    m.add('mirror', fv, fuv, ft, toward=EYE)
    # driver's door: panel with an armrest and a handle recess, the window sill, and the side glass above it
    DY = YC - 74
    rows = []
    for x in np.linspace(78, -70, 16):
        prof = [(DY - 3, 98), (DY, 96.5), (DY + 1.0, 90), (DY + 1.5, 80)]
        arm = 6.0 * smoothstep(40, 20, x) * smoothstep(-60, -40, x)
        prof += [(DY + 1.5 + arm, 76), (DY + 1.5 + arm, 72), (DY + 1.0, 66), (DY, 50)]
        rows.append([(x, y, z) for y, z in prof])
